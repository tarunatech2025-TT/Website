import { NextResponse } from 'next/server';
import nodemailer from 'nodemailer';

function isValidEmail(email) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(email).trim());
}

/** Phone: at least 7 digits, allows +, spaces, dashes, parens */
function isValidPhone(phone) {
  return /^[\d\s\+\-\(\)]{7,20}$/.test(String(phone).trim());
}

/** Strip HTML tags and trim */
function sanitize(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/<[^>]*>/g, '').trim();
}

/** Submitted time in IST */
function submittedAt() {
  return new Date().toLocaleString('en-IN', {
    timeZone: 'Asia/Kolkata',
    dateStyle: 'full',
    timeStyle: 'short',
  });
}

/** Shared row builder for HTML emails */
function row(label, value) {
  const safe = sanitize(value) || '—';
  return `
    <tr>
      <td style="padding:8px 12px;font-weight:600;color:#a78bfa;width:160px;vertical-align:top;white-space:nowrap;">
        ${label}
      </td>
      <td style="padding:8px 12px;color:#e2e8f0;">
        ${safe}
      </td>
    </tr>`;
}

