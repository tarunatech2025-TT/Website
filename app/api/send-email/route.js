// Simple in-memory rate limiter: max 5 submissions per IP per minute
const rateLimitMap = new Map();
function checkRateLimit(ip) {
  const now = Date.now();
  const window = 60_000; // 1 minute
  const max = 5;
  const entry = rateLimitMap.get(ip) || { count: 0, start: now };
  if (now - entry.start > window) {
    rateLimitMap.set(ip, { count: 1, start: now });
    return true;
  }
  if (entry.count >= max) return false;
  rateLimitMap.set(ip, { count: entry.count + 1, start: entry.start });
  return true;
}

export async function POST(request) {
  // ── Rate limit ──────────────────────────────────────────────
  const ip =
    request.headers.get('x-forwarded-for')?.split(',')[0]?.trim() ||
    request.headers.get('x-real-ip') ||
    'unknown';

  if (!checkRateLimit(ip)) {
    return NextResponse.json(
      { success: false, error: 'Too many requests. Please wait a moment and try again.' },
      { status: 429 }
    );
  }

  // ── Parse body ──────────────────────────────────────────────
  let body;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json(
      { success: false, error: 'Invalid request body.' },
      { status: 400 }
    );
  }

  const { formType, ...fields } = body;

  // ── Validate formType ───────────────────────────────────────
  const VALID_FORM_TYPES = ['consultation', 'course-enrollment', 'contact', 'product-demo'];
  if (!formType || !VALID_FORM_TYPES.includes(formType)) {
    return NextResponse.json(
      { success: false, error: 'Invalid form type.' },
      { status: 400 }
    );
  }

  // ── Validate shared required fields (email + phone) ─────────
  const email = sanitize(fields.email);
  const phone = sanitize(fields.phone);

  if (!email || !isValidEmail(email)) {
    return NextResponse.json(
      { success: false, error: 'Please provide a valid email address.' },
      { status: 422 }
    );
  }
  if (!phone || !isValidPhone(phone)) {
    return NextResponse.json(
      { success: false, error: 'Please provide a valid phone number.' },
      { status: 422 }
    );
  }

  // ── Per-form validation ─────────────────────────────────────
  if (formType === 'consultation') {
    if (!sanitize(fields.name)) {
      return NextResponse.json({ success: false, error: 'Name is required.' }, { status: 422 });
    }
  }

  if (formType === 'course-enrollment') {
    if (!sanitize(fields.name)) {
      return NextResponse.json({ success: false, error: 'Full name is required.' }, { status: 422 });
    }
    if (!sanitize(fields.course)) {
      return NextResponse.json({ success: false, error: 'Please select a course.' }, { status: 422 });
    }
  }

  if (formType === 'contact') {
    if (!sanitize(fields.name)) {
      return NextResponse.json({ success: false, error: 'Name is required.' }, { status: 422 });
    }
    if (!sanitize(fields.message)) {
      return NextResponse.json({ success: false, error: 'Message is required.' }, { status: 422 });
    }
  }

  if (formType === 'product-demo') {
    if (!sanitize(fields.name)) {
      return NextResponse.json({ success: false, error: 'Name is required.' }, { status: 422 });
    }
    if (!sanitize(fields.product)) {
      return NextResponse.json({ success: false, error: 'Product name is required.' }, { status: 422 });
    }
  }

  // ── Check env vars ──────────────────────────────────────────
  const EMAIL_USER     = process.env.EMAIL_USER;
  const EMAIL_PASS     = process.env.EMAIL_PASS;
  const BUSINESS_EMAIL = process.env.BUSINESS_EMAIL;

  if (!EMAIL_USER || !EMAIL_PASS || !BUSINESS_EMAIL) {
    console.error('[send-email] Missing EMAIL_USER, EMAIL_PASS, or BUSINESS_EMAIL env vars');
    return NextResponse.json(
      { success: false, error: 'Email service is not configured. Please contact us directly.' },
      { status: 500 }
    );
  }

  // ── Build email content ─────────────────────────────────────
  let emailContent;
  const sanitizedFields = Object.fromEntries(
    Object.entries(fields).map(([k, v]) => [k, sanitize(v)])
  );

  switch (formType) {
    case 'consultation':
      emailContent = buildConsultationEmail(sanitizedFields);
      break;
    case 'course-enrollment':
      emailContent = buildCourseEnrollmentEmail(sanitizedFields);
      break;
    case 'contact':
      emailContent = buildContactEmail(sanitizedFields);
      break;
    case 'product-demo':
      emailContent = buildProductDemoEmail(sanitizedFields);
      break;
  }

  // ── Send via Nodemailer ─────────────────────────────────────
  const transporter = nodemailer.createTransport({
    service: 'gmail',
    auth: { user: EMAIL_USER, pass: EMAIL_PASS },
  });

  try {
    await transporter.sendMail({
      from: `"Taruna Technology Website" <${EMAIL_USER}>`,
      to: BUSINESS_EMAIL,
      replyTo: sanitizedFields.email,
      subject: emailContent.subject,
      text: emailContent.text,
      html: emailContent.html,
    });

    return NextResponse.json({ success: true });
  } catch (err) {
    console.error('[send-email] Nodemailer error:', err?.message || err);
    return NextResponse.json(
      { success: false, error: 'Failed to send email. Please try again or contact us directly.' },
      { status: 500 }
    );
  }
}
