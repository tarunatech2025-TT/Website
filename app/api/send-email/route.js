function buildConsultationEmail(data) {
  const { name, email, phone, service, message } = data;
  const html = buildEmail({
    title: '⚡ New Consultation Request',
    accentColor: '#7c3aed,#a855f7',
    rows: [
      row('Name', name),
      row('Email', email),
      row('Phone', phone),
      row('Service Interested', service || 'Not selected'),
      row('Project Description', message || 'Not provided'),
      row('Submitted', submittedAt()),
    ].join(''),
  });
  const text = [
    'NEW CONSULTATION REQUEST — Taruna Technology',
    '─'.repeat(40),
    `Name:               ${sanitize(name)}`,
    `Email:              ${sanitize(email)}`,
    `Phone:              ${sanitize(phone)}`,
    `Service Interested: ${sanitize(service) || 'Not selected'}`,
    `Project Description:${sanitize(message) || 'Not provided'}`,
    `Submitted:          ${submittedAt()}`,
  ].join('\n');
  return { subject: 'New Consultation Request — Taruna Technology', html, text };
}

